def build():
    out = []
    n = 0
    rows = [l.split("|") for l in QA]
    topics = {}
    for r in rows:
        topics.setdefault(r[6], []).append(r)
    for i, (q, a, w, emo, ref, lv, topic) in enumerate(rows):
        pw = who(i, 121)
        prompt = q
        n += 1
        out.append(Q(f"soc-{n:03d}", "사회", prompt, [a] + w.split(","), 0, level=int(lv),
                     image=img(None if ref == "-" else ref, emo), group="soc-" + topic, explain=f"[{topic}]"))
    # 사진 보고 장소·물건 이름 맞히기 (사진이 있는 것)
    named = [(r[1], r[4], r[3], r[6]) for r in rows if r[4] != "-"]
    names = [x[0] for x in named]
    for i, (a, ref, emo, topic) in enumerate(named):
        R = random.Random(500 + i)
        same = [x[0] for x in named if x[3] == topic and x[0] != a]
        pool = same if len(same) >= 2 else [x for x in names if x != a]
        n += 1
        out.append(Q(f"soc-{n:03d}", "사회", "사진을 보고 알맞은 이름을 골라요.", [a] + R.sample(pool, 2), 0, level=2,
                     image=img(ref, emo), pool=pool, group="soc-photo"))
    # 옛날 vs 오늘날 짝 맞히기
    PAIRS = [("우물", "수도꼭지", "💧"), ("호롱불", "전등", "💡"), ("맷돌", "믹서기", "🌀"), ("빨래터", "세탁기", "🧺"),
             ("가마", "자동차", "🚗"), ("봉화", "전화", "📞"), ("부채", "에어컨", "❄️"), ("아궁이", "가스레인지", "🔥"),
             ("짚신", "운동화", "👟"), ("서당", "학교", "🏫"), ("엽전", "카드", "💳"), ("붓", "볼펜", "🖊️")]
    olds = [p[0] for p in PAIRS]; news = [p[1] for p in PAIRS]
    for i, (old, new, emo) in enumerate(PAIRS):
        R = random.Random(800 + i)
        n += 1
        out.append(Q(f"soc-{n:03d}", "사회", f"옛날의 '{old}'은(는) 오늘날 무엇이 되었을까요?", [new] + R.sample([x for x in news if x != new], 2), 0,
                     level=2, image=img(None, emo), pool=[x for x in news if x != new], group="soc-oldnew"))
        n += 1
        out.append(Q(f"soc-{n:03d}", "사회", f"오늘날의 '{new}'처럼 옛날에 쓰던 것은?", [old] + R.sample([x for x in olds if x != old], 2), 0,
                     level=3, image=img(None, emo), pool=[x for x in olds if x != old], group="soc-newold"))
    return out
