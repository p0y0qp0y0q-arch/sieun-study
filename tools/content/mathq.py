# 같은 템플릿을 물건을 바꿔 여러 문제로 (물건이 들어간 템플릿 × 물건 조합)
def build():
    objs = []
    for line in OBJS:
        nm, u, emo, ref = line.split("|")
        objs.append({"name": nm, "unit": u, "emoji": emo, "image": img(None if ref == "-" else ref, emo)})
    out = []
    n = 0
    for i, line in enumerate(T):
        t, a, b, c, ans, cond, show = (line.split("|") + [""] * 7)[:7]
        def rng(s):
            if not s:
                return None
            x, y = s.split("-")
            return [int(x), int(y)]
        uses_obj = "{o}" in t
        variants = 6 if uses_obj else 1   # 물건 이름이 들어간 문제는 물건 묶음별로 6가지
        for v in range(variants):
            n += 1
            lv = 1
            hi = max([x[1] for x in [rng(a), rng(b), rng(c)] if x] or [0])
            if hi > 10 or "*" in ans or "/" in ans:
                lv = 2
            if hi > 20:
                lv = 3
            d = {"id": f"math-w{n:03d}", "subject": "수학", "type": "word", "template": t,
                 "ranges": {k: rng(s) for k, s in (("a", a), ("b", b), ("c", c)) if rng(s)},
                 "ans": ans, "level": lv, "group": "math-word"}
            if cond:
                d["cond"] = cond
            if show:
                d["show"] = show
            if uses_obj:
                d["objs"] = [o["name"] for o in objs[v::6]]
            out.append(d)
    return out, objs

