def parse():
    books, cur = [], None
    for line in BOOKS.strip().splitlines():
        if line.startswith("#"):
            no, title, area, emo = line[1:].split("|")
            cur = {"no": int(no), "t": title, "area": area, "emo": emo, "qs": []}
            books.append(cur)
        else:
            cur["qs"].append(line.split("|"))
    return sorted(books, key=lambda b: b['no'])

def build():
    out = []
    n = 0
    for b in parse():
        for q, a, w, lv in b["qs"]:
            n += 1
            out.append(Q(f"sci-{n:03d}", "과학", q, [a] + w.split(","), 0, level=int(lv), display=b["emo"], displayClass="scene",
                         html=f'<div class="book-tag">📚 {b["no"]}. {b["t"]}</div>', group=f"sci-{b['area']}",
                         explain=f"『{b['t']}』 ({b['area']})"))
    return out
