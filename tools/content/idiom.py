def build():
    out = []
    n = 0
    def add(prompt, choices, lv, group, **kw):
        nonlocal n
        n += 1
        out.append(Q(f"idm-{n:03d}", "관용구", prompt, choices, 0, level=lv, group=group, **kw))
    rows = [l.split("|") for l in IDIOMS]
    names = [r[0] for r in rows]
    for i, (w, mean, wr, sit, lv) in enumerate(rows):
        R = random.Random(i)
        add("이 말은 무슨 뜻일까요?", [mean] + wr.split(","), int(lv), "idm-mean", display=w, speakChoices=True)
        if sit != "-":
            others = [x for x in names if x != w]
            add("이럴 때 쓰는 말은 무엇일까요?", [w] + R.sample(others, 2), int(lv), "idm-situ", pool=others, speakChoices=True,
                display=sit, speak=f"{sit} 이럴 때 쓰는 말은 무엇일까요?")
    prow = [l.split("|") for l in PROVERBS]
    means = [r[3] for r in prow]
    for i, (a, b, wr, mean, lv) in enumerate(prow):
        R = random.Random(100 + i)
        add("속담을 완성해요. 빈칸에 알맞은 말은?", [b] + wr.split(","), int(lv), "prv-fill", display=f"{a} (  ?  )",
            speak=f"속담을 완성해요. {a}, 빈칸.", speakChoices=True, explain=f"{a} {b}: {mean}")
        others = [x for x in means if x != mean]
        add(f"'{a} {b}'{josa(b, '은', '는')} 무슨 뜻일까요?", [mean] + R.sample(others, 2), max(2, int(lv)), "prv-mean", pool=others, speakChoices=True)
    return out
