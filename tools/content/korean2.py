CHO = "ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ"
def chosung(w):
    return "".join(CHO[(ord(c) - 0xAC00) // 588] if 0xAC00 <= ord(c) <= 0xD7A3 else c for c in w)
NEAR = {"ㄱ": "ㄲㅋ", "ㄲ": "ㄱㅋ", "ㅋ": "ㄱㄲ", "ㄷ": "ㄸㅌ", "ㄸ": "ㄷㅌ", "ㅌ": "ㄷㄸ", "ㅂ": "ㅃㅍ", "ㅃ": "ㅂㅍ", "ㅍ": "ㅂㅃ",
        "ㅅ": "ㅆㅈ", "ㅆ": "ㅅㅈ", "ㅈ": "ㅉㅊ", "ㅉ": "ㅈㅊ", "ㅊ": "ㅈㅉ", "ㄴ": "ㄹㅁ", "ㄹ": "ㄴㅁ", "ㅁ": "ㄴㅂ", "ㅇ": "ㅎㄴ", "ㅎ": "ㅇㄱ"}


def build(words):
    """words: korean.py 의 (낱말, 오답, 이모지, 사진ref) 목록 — 초성 퀴즈 사진에 씀"""
    out = []
    n = 0
    def add(prompt, choices, lv, group, **kw):
        nonlocal n
        n += 1
        out.append(Q(f"kor2-{n:03d}", "국어", prompt, choices, 0, level=lv, group=group, **kw))
    for l in ANTONYM:
        w, a, wr, e, lv = l.split("|")
        add(f"'{w}'의 반대말은 무엇일까요?", [a] + wr.split(","), int(lv), "kor-ant", display=e)
    allant = [l.split("|")[1] for l in ANTONYM]
    for l in SYNONYM:
        w, a, wr, e, lv = l.split("|")
        add(f"'{w}'와(과) 뜻이 비슷한 말은?".replace("와(과)", "과" if (ord(w[-1]) - 0xAC00) % 28 else "와"), [a] + wr.split(","), int(lv), "kor-syn", display=e)
    for l in MIMIC:
        s, a, wr, e, lv, kind = l.split("|")
        add(f"빈칸에 알맞은 흉내 내는 말은?", [a] + wr.split(","), int(lv), "kor-mimic", display=e + "  " + s.replace("□", "(  ?  )"),
            speak="빈칸에 알맞은 흉내 내는 말은? " + s.replace("□", ", 빈칸,"))
    for l in HONOR:
        s, a, wr, e, lv = l.split("|")
        add("높임말로 바르게 말해요. 빈칸에 알맞은 말은?", [a] + wr.split(","), int(lv), "kor-honor", display=e + "  " + s.replace("□", "(  ?  )"),
            speak="높임말로 바르게 말해요. " + s.replace("□", ", 빈칸,"), speakChoices=False)
    for l in CONJ:
        s1, s2, a, wr, e, lv = l.split("|")
        add("두 문장을 이어 주는 알맞은 말은?", [a] + wr.split(","), int(lv), "kor-conj", display=f"{e}  {s1} (  ?  ) {s2}",
            speak=f"두 문장을 이어 주는 알맞은 말은? {s1} 빈칸, {s2}")
    # 초성 퀴즈
    R = random.Random(7)
    wl = [x for x in words if 2 <= len(x[0]) <= 4 and all(0xAC00 <= ord(c) <= 0xD7A3 for c in x[0])]
    for i, (w, _, e, ref) in enumerate(wl):
        c = chosung(w)
        if i % 2 == 0:
            # 그림 보고 알맞은 초성 고르기
            wrong = set()
            for _ in range(20):
                k = R.randrange(len(c)); alt = NEAR.get(c[k], "ㄱ")
                cand = c[:k] + R.choice(alt) + c[k + 1:]
                if cand != c: wrong.add(cand)
                if len(wrong) >= 2: break
            if len(wrong) < 2: continue
            add("그림을 보고 첫소리(초성)가 맞는 것을 골라요.", [c] + sorted(wrong)[:2], 1, "kor-cho", image=img(ref, e), speakChoices=False)
        else:
            # 초성 + 그림 힌트 → 낱말 고르기 (같은 첫소리 낱말을 오답으로)
            same = [x[0] for x in wl if x[0] != w and chosung(x[0])[0] == c[0]]
            others = [x[0] for x in wl if x[0] != w]
            wr = R.sample(same, 2) if len(same) >= 2 else R.sample(others, 2)
            add(f"첫소리가 '{c}'인 낱말은 무엇일까요?", [w] + wr, 2, "kor-cho", display=c, speakChoices=False,
                speak=f"첫소리가 {' '.join(c)} 인 낱말은 무엇일까요?")
    return out
